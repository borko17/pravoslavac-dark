    private static final int N = COLORS.length;
    private static final String[] STEM = new String[N];
    private static final boolean[] FIXED = new boolean[N];
    private static final float[][] HSL = new float[N][];

    static {
        for (int i = 0; i < N; i++) {
            String st = COLORS[i][0];
            FIXED[i] = st.startsWith("=");
            STEM[i] = FIXED[i] ? st.substring(1) : st;
            HSL[i] = RandomTheme.rgbToHsl(0xFF000000 | Integer.parseInt(COLORS[i][1], 16));
        }
    }

    private static int idx(String stem) {
        for (int i = 0; i < N; i++) {
            if (STEM[i].equals(stem)) return i;
        }
        throw new IllegalStateException(stem);
    }

    private static String ending(int gender, String stem) {
        if (gender == MASC) return stem.endsWith("ов") ? "" : "и"; // присвојни: "лососов", "боров"
        if (gender == FEM) return "а";
        char c = stem.charAt(stem.length() - 1);
        return "љњжшчћџђј".indexOf(c) >= 0 ? "е" : "о";
    }

    private static String form(int gender, int i) {
        return FIXED[i] ? STEM[i] : STEM[i] + ending(gender, STEM[i]);
    }

    private static float hueDist(float a, float b) {
        float d = Math.abs(a - b) % 360f;
        return d > 180f ? 360f - d : d;
    }

    private static final int POOL_DARK = 0;     // tamne pozadine: tamna imena (svjetlina do 0.45)
    private static final int POOL_LIGHT = 1;    // svijetle pozadine: svijetla i pastelna imena (od 0.55)
    private static final int POOL_HOLIDAY = 2;  // boja praznika: srednje svijetla imena

    private static boolean inPool(int pool, int i) {
        float s = HSL[i][1];
        float l = HSL[i][2];
        if (s < 0.25f) return false;
        switch (pool) {
            case POOL_DARK: return l <= 0.45f;
            case POOL_LIGHT: return l >= 0.55f;
            default: return l >= 0.35f && l <= 0.9f;
        }
    }

    /** Boja iz skupa sa najblizom nijansom; izmedju skoro jednako blizih bira nasumicno. -1 ako je skup prazan. */
    private static int nearest(int pool, float hue, Random r) {
        float best = 1000f;
        for (int i = 0; i < N; i++) {
            if (inPool(pool, i)) best = Math.min(best, hueDist(hue, HSL[i][0]));
        }
        if (best >= 1000f) return -1;
        int[] ok = new int[N];
        int n = 0;
        for (int i = 0; i < N; i++) {
            if (inPool(pool, i) && hueDist(hue, HSL[i][0]) <= best + 8f) ok[n++] = i;
        }
        return ok[r.nextInt(n)];
    }

    /** Pridjev za pozadinu: ime najblize boje (tamna imena za tamne, svijetla za svijetle pozadine). */
    private static String bgAdjective(int gender, int bg, Random r) {
        float[] hsl = RandomTheme.rgbToHsl(bg);
        boolean light = hsl[2] >= 0.5f;
        if (hsl[1] < NEUTRAL) {
            if (!light) {
                if (hsl[2] < 0.05f) return form(gender, idx("црн"));
                return form(gender, idx(r.nextBoolean() ? "антрацитн" : "графитн"));
            }
            if (hsl[2] >= 0.985f) return form(gender, idx("бел"));
            return form(gender, idx(r.nextBoolean() ? "сребрн" : "пепељаст"));
        }
        int i = nearest(light ? POOL_LIGHT : POOL_DARK, hsl[0], r);
        return form(gender, i < 0 ? idx("сив") : i);
    }

    /** Pridjev za boju praznika (bez prefiksa). */
    private static String holidayAdjective(int gender, float[] hsl, Random r) {
        if (hsl[1] < NEUTRAL) {
            String[] grey = { "сребрн", "сив", "пепељаст", "челичн" };
            return form(gender, idx(grey[r.nextInt(grey.length)]));
        }
        int i = nearest(POOL_HOLIDAY, hsl[0], r);
        return i < 0 ? form(gender, idx("сив")) : form(gender, i);
    }

    private static boolean validBgAdjective(int gender, String adj) {
        for (int i = 0; i < N; i++) {
            String f = form(gender, i);
            if (adj.equals(f)) return true;
        }
        return false;
    }

    private static boolean validHolidayAdjective(int gender, String adj) {
        for (int i = 0; i < N; i++) {
            if (adj.equals(form(gender, i))) return true;
        }
        return false;
    }

    private static String capitalize(String s) {
        return s.isEmpty() ? s : Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }

    private static boolean validAdjective(int gender, String adj) {
        // pridjev mora poceti velikim slovom; ostalo se provjerava bez njega
        if (adj.isEmpty() || !Character.isUpperCase(adj.charAt(0))) return false;
        adj = Character.toLowerCase(adj.charAt(0)) + adj.substring(1);
        if (gender != NEUT) return validBgAdjective(gender, adj);
        int dash = adj.indexOf('-');
        if (dash < 0) return validBgAdjective(gender, adj);
        if (dash == 0) return false;
        return validBgAdjective(gender, adj.substring(0, dash))
                && validHolidayAdjective(gender, adj.substring(dash + 1));
    }

    // ------------------------------------------------------------------ nazivi

    private static String randomNoun(int gender, Random r) {
        String[] nouns = NOUNS[gender];
        return nouns[r.nextInt(nouns.length)];
    }

    /**
     * Naziv za zadati rod. bg je boja pozadine (0xRRGGBB ili 0xffRRGGBB); holiday je boja praznika i koristi se
     * samo za srednji rod.
     */
    static String make(int gender, Random r, int bg, int holiday) {
        String adj = bgAdjective(gender, bg, r);
        if (gender == NEUT) {
            // slicna nijansa pozadine i praznika se ne ponavlja ("тамнозелено", a ne "тамнозелено-зелено")
            float[] b = RandomTheme.rgbToHsl(bg);
            float[] h = RandomTheme.rgbToHsl(holiday);
            boolean bn = b[1] < NEUTRAL;
            boolean hn = h[1] < NEUTRAL;
            boolean similar = (bn && hn) || (!bn && !hn && hueDist(b[0], h[0]) < 20f);
            if (!similar) {
                String ha = holidayAdjective(gender, h, r);
                if (!adj.endsWith(ha)) adj += "-" + ha;
            }
        }
        return PREFIX + capitalize(adj) + " " + randomNoun(gender, r);
    }

    /**
     * Naziv koji nije u skupu zauzetih: mijenja se samo imenica iz zadatog naziva (pridjev ostaje), a poslije
     * 200 pokusaja dodaje broj.
     */
    static String unique(int gender, Random r, Set<String> taken, String name) {
        int sp = name.indexOf(' ', PREFIX.length());
        String start = sp < 0 ? name : name.substring(0, sp + 1);
        String n = name;
        for (int i = 0; i < 200 && taken.contains(n); i++) n = start + randomNoun(gender, r);
        int k = 2;
        String base = n;
        while (taken.contains(n)) n = base + " " + (k++);
        return n;
    }

    /**
     * Rod ako naziv izgleda kao naziv generisane teme (prefiks, pridjev boje i imenica iz spiska, rod se slaze),
     * inace -1. Preimenovana tema se zato ne prepoznaje.
     */
    static int parse(String name) {
        if (name == null || !name.startsWith(PREFIX)) return -1;
        String rest = name.substring(PREFIX.length());
        int sp = rest.indexOf(' ');
        if (sp <= 0) return -1;
        String adj = rest.substring(0, sp);
        // unique() moze dodati sufiks " 2", " 3"...
        String noun = rest.substring(sp + 1).replaceFirst(" \\d+$", "");
        for (int g = 0; g < NOUNS.length; g++) {
            for (String n : NOUNS[g]) {
                if (n.equals(noun) && validAdjective(g, adj)) return g;
            }
        }
        return -1;
    }
